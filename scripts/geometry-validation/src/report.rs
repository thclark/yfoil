//! The run's index (`README.md`, `README.tex`, `summary.json`) and the study's documentation
//! products: the naca456 page under Engineering validation, and each family's sheet beside the
//! Aerofoil families page that embeds it.

use crate::naca456::CaseComparison;
use crate::study::{validation_set, SeriesStudy, N_NODES};
use cr_libm::hypot;
use std::fs;
use std::io::Write;
use std::path::Path;

fn te_gap(g: &yfoil::geometry::Geometry) -> f64 {
    let n = g.x.len();
    hypot(g.x[0] - g.x[n - 1], g.y[0] - g.y[n - 1])
}

fn max_thickness(g: &yfoil::geometry::Geometry) -> f64 {
    // the largest vertical extent between the two surfaces at the sampled stations, which are
    // symmetric in x for a symmetric section and near enough for the table
    let n = g.x.len() / 2;
    (0..n)
        .map(|i| (g.y[i] - g.y[g.x.len() - 1 - i]).abs())
        .fold(0.0, f64::max)
}

pub fn write_summary_json(run_dir: &Path, series: &[&SeriesStudy], comparison: &[CaseComparison]) {
    let member = |m: &crate::study::Member| {
        serde_json::json!({
            "designation": m.designation, "label": m.label, "value": m.value, "file": format!("{}.json", m.slug),
            "n_nodes": m.geometry.x.len(), "te_gap": te_gap(&m.geometry), "max_thickness": max_thickness(&m.geometry),
            "generator": m.geometry.generator,
        })
    };
    let series_json: Vec<serde_json::Value> = series
        .iter()
        .map(|s| {
            serde_json::json!({
                "slug": s.slug, "title": s.title, "parameters": s.parameters, "references": s.references,
                "validation_use": s.validation_use, "alt": sheet_alt(s), "family_page": family_page(s.slug),
                "default": member(&s.default),
                "panels": s.panels.iter().map(|p| serde_json::json!({
                    "slug": p.slug, "title": p.title, "members": p.members.iter().map(member).collect::<Vec<_>>(),
                })).collect::<Vec<_>>(),
            })
        })
        .collect();
    let cmp: Vec<serde_json::Value> = comparison
        .iter()
        .map(|c| {
            serde_json::json!({
                "case": c.slug, "designation": c.designation, "family": c.family, "series": c.series, "stations": c.stations,
                "worst_rel": { "y_t": c.y_t, "dy_t_dx": c.y_t_slope, "y_c": c.y_c, "dy_c_dx": c.y_c_slope, "surface": c.surface },
            })
        })
        .collect();
    fs::write(
        run_dir.join("summary.json"),
        serde_json::to_string_pretty(&serde_json::json!({
            "n_nodes": N_NODES, "series": series_json, "naca456_comparison": cmp,
            "validation_set": validation_set().iter().map(|v| serde_json::json!({
                "designation": v.designation, "series": v.series, "cli": v.cli, "why": v.why, "references": v.references,
            })).collect::<Vec<_>>(),
        }))
        .unwrap(),
    )
    .unwrap();
}

fn comparison_table_md(comparison: &[&CaseComparison]) -> String {
    let mut t = String::from(
        "| Case | Section | Thickness form | Stations | worst Δy_t | worst Δ(dy_t/dx) | worst Δy_c | worst Δ(dy_c/dx) | worst Δ surface |\n|---|---|---|---:|---:|---:|---:|---:|---:|\n",
    );
    for c in comparison {
        t += &format!(
            "| `{}` | {} | {} | {} | {:.1e} | {:.1e} | {:.1e} | {:.1e} | {:.1e} |\n",
            c.slug, c.designation, c.family, c.stations, c.y_t, c.y_t_slope, c.y_c, c.y_c_slope, c.surface
        );
    }
    t
}

fn comparison_note() -> &'static str {
    "Differences are `|Δ| / max(|yFoil|, |naca456|, 1)`, the worst over naca456's 98 \"very fine\" stations. \
     The closed-form families agree to round-off. The 6-series mean lines differ by naca456's 10-digit π \
     (1.1e-10 relative). The 6-series thickness forms differ by naca456's own root tolerance: it finds the \
     station on the arc-length spline with Brent's method at 1e-6 and reports the ordinate at the station \
     reached, so its ordinates are off by up to 1e-6 × |dy_t/dx| (largest at the nose); yFoil inverts to \
     round-off. The tolerances in `tests/application/naca456.rs` are derived from exactly that \
     (`tests/common/utilities/tolerances.rs`). naca456 reports the aft slope of the 4-digit modified form as \
     dy/d(1 − x); the sign is restored before comparing."
}

pub fn write_index(run_dir: &Path, series: &[&SeriesStudy], comparison: &[CaseComparison]) {
    let mut f = fs::File::create(run_dir.join("README.md")).unwrap();
    writeln!(f, "# Geometry validation\n").unwrap();
    writeln!(
        f,
        "Generated by `cargo run --release -p geometry-validation` (provenance in `metadata.json`, every drawn section's \
         geometry with its `generator` record under `<series>/<panel>/`, table data in `summary.json`). Each figure is \
         one generator family: one panel per parameter, the family default in black on top, the members behind it \
         coloured by parameter value (YlGnBu, lightest = smallest), {N_NODES} nodes each, all panels on the same axes \
         (x −0.2…1.2, y −0.5…0.5, linked, sized for equal scale).\n"
    )
    .unwrap();
    writeln!(
        f,
        "Figures are ironlab figures built in Rust from `summary.json` and the geometry files (`--render <run_dir>` \
         redraws them without rerunning the study), at ironlab's default width and font, and come as `.fig` (open \
         in the ironlab viewer) and PDF; include the PDF at natural size (`\\includegraphics{{...pdf}}`, no `width=`, \
         no `\\resizebox`).\n"
    )
    .unwrap();
    writeln!(f, "| Figure | Family | Default (black) | Panels |\n|---|---|---|---|").unwrap();
    for s in series {
        writeln!(
            f,
            "| [{0}.fig]({0}.fig) | {1} | {2} | {3} |",
            s.slug,
            s.title,
            s.default.designation,
            s.panels.iter().map(|p| p.title.as_str()).collect::<Vec<_>>().join("; ")
        )
        .unwrap();
    }
    for s in series {
        writeln!(f, "\n## {}\n", s.title).unwrap();
        writeln!(f, "Parameters: {}.\n", s.parameters).unwrap();
        writeln!(f, "{}\n", s.description).unwrap();
        for p in &s.panels {
            writeln!(f, "### {}\n", p.title).unwrap();
            writeln!(
                f,
                "| Section | Parameter | Nodes | TE gap | Max thickness | File |\n|---|---|---:|---:|---:|---|"
            )
            .unwrap();
            for m in &p.members {
                writeln!(
                    f,
                    "| {} | {} | {} | {:.2e} | {:.4} | `{}/{}/{}.json` |",
                    m.designation,
                    m.label,
                    m.geometry.x.len(),
                    te_gap(&m.geometry),
                    max_thickness(&m.geometry),
                    s.slug,
                    p.slug,
                    m.slug
                )
                .unwrap();
            }
            writeln!(f).unwrap();
        }
    }
    if !comparison.is_empty() {
        writeln!(f, "\n## Generators against naca456\n").unwrap();
        writeln!(f, "{}\n", comparison_note()).unwrap();
        write!(f, "{}", comparison_table_md(&comparison.iter().collect::<Vec<_>>())).unwrap();
    }
}

fn tex_escape(s: &str) -> String {
    s.replace('_', "\\_")
        .replace('%', "\\%")
        .replace('&', "\\&")
        .replace('#', "\\#")
}

pub fn write_index_tex(run_dir: &Path, series: &[&SeriesStudy], comparison: &[CaseComparison]) {
    let mut f = fs::File::create(run_dir.join("README.tex")).unwrap();
    let w = |f: &mut fs::File, s: &str| writeln!(f, "{s}").unwrap();
    w(&mut f, "\\documentclass[11pt,a4paper]{article}");
    w(&mut f, "\\usepackage[margin=20mm]{geometry}");
    w(&mut f, "\\usepackage[utf8]{inputenc}");
    w(&mut f, "\\usepackage{amsmath,booktabs,longtable,siunitx,graphicx,url}");
    w(&mut f, "\\title{Geometry validation}");
    w(
        &mut f,
        "\\author{yFoil project}\n\\date{\\today}\n\\begin{document}\n\\maketitle",
    );
    w(&mut f, &format!(
        "\\noindent Generated by \\texttt{{cargo run --release -p geometry-validation}} (provenance in \\texttt{{metadata.json}}, \
         table data in \\texttt{{summary.json}}, every drawn section's geometry under \\texttt{{<series>/<panel>/}}). Each figure \
         is one generator family: one panel per parameter, the family default in black on top, the members behind it coloured \
         by parameter value (YlGnBu, lightest = smallest), {N_NODES} nodes each, all panels on the same axes \
         ($x$ from $-0.2$ to $1.2$, $y$ from $-0.5$ to $0.5$, sized for equal scale)."
    ));
    w(
        &mut f,
        "\n\\section*{Figures}\n\\noindent Figures are ironlab figures exported to PDF at ironlab's default width \
         and font, so they are included at natural size: no \\texttt{width=} and no \\texttt{\\resizebox}.",
    );
    for s in series {
        w(&mut f, &format!("\n\\section*{{{}}}", tex_escape(s.title)));
        w(
            &mut f,
            &format!("\\noindent Parameters: {}.\n", tex_escape(s.parameters)),
        );
        w(&mut f, &format!("\\noindent {}\n", tex_escape(s.description)));
        w(
            &mut f,
            &format!(
                "\\begin{{figure}}[p]\\centering\\includegraphics{{{}.pdf}}\\caption{{{}: {} nodes; default {} in black, \
                 members coloured by parameter value.}}\\end{{figure}}",
                s.slug,
                tex_escape(s.title),
                N_NODES,
                tex_escape(&s.default.designation)
            ),
        );
    }
    if !comparison.is_empty() {
        w(&mut f, "\n\\section*{Generators against naca456}");
        w(&mut f, &format!("\\noindent {}\n", tex_escape(comparison_note())));
        w(
            &mut f,
            "{\\renewcommand\\arraystretch{1.1}\\small\n\\begin{longtable}{@{}llrrrrrr@{}}\\toprule",
        );
        w(&mut f, "Case & Thickness form & Stations & $\\Delta y_t$ & $\\Delta y_t'$ & $\\Delta y_c$ & $\\Delta y_c'$ & $\\Delta$ surface \\\\ \\midrule\\endhead");
        for c in comparison {
            w(
                &mut f,
                &format!(
                    "{} & {} & {} & \\num{{{:.1e}}} & \\num{{{:.1e}}} & \\num{{{:.1e}}} & \\num{{{:.1e}}} & \\num{{{:.1e}}} \\\\",
                    tex_escape(&c.designation),
                    c.family,
                    c.stations,
                    c.y_t,
                    c.y_t_slope,
                    c.y_c,
                    c.y_c_slope,
                    c.surface
                ),
            );
        }
        w(&mut f, "\\bottomrule\\end{longtable}}");
    }
    w(&mut f, "\\end{document}");
}

/// The page `--docs` writes, relative to `docs/`: the naca456 comparison, under Engineering validation
pub const NACA456_PAGE: &str = "engineering-validation/generated-sections-against-naca456.md";

/// The Aerofoil families section of the user documentation, relative to `docs/`. Its pages are
/// written by hand (the definitions); this study draws the figures they embed, one per generator
/// family, into the directory beside the page that shows the family.
pub const FAMILIES_DIR: &str = "using-yfoil/aerofoil-families";

/// The Aerofoil families page that shows a generator family (`SeriesStudy::slug`): the 4-digit
/// modified form and the 6A-series share a page with the family they modify
pub fn family_page(slug: &str) -> &'static str {
    match slug {
        "naca-4-digit" | "naca-4-digit-modified" => "naca-4-digit-and-4-digit-modified",
        "naca-5-digit" => "naca-5-digit-including-reflex",
        "naca-16-series" => "naca-16-series",
        "naca-6-series" | "naca-6a-series" => "naca-6-and-6a-series",
        "karman-trefftz" => "karman-trefftz-sections",
        other => panic!("{other}: no Aerofoil families page shows this family"),
    }
}

/// The alt text (and caption) of a family's sheet, as the family page embeds it
pub fn sheet_alt(s: &SeriesStudy) -> String {
    let panels = s.panels.iter().map(|p| p.title.as_str()).collect::<Vec<_>>().join("; ");
    format!("{}: default {} in black; {}", s.title, s.default.designation, panels)
}

/// Links from the naca456 page (`docs/engineering-validation/`) into the user documentation
const USING: &str = "../using-yfoil";

fn reference_links(keys: &[&str]) -> String {
    keys.iter()
        .map(|r| format!("[{r}]({USING}/bibliography.md#{r})"))
        .collect::<Vec<_>>()
        .join(", ")
}

/// The study's documentation products: the naca456 page (`NACA456_PAGE`) and each family's sheet,
/// copied into `FAMILIES_DIR/<family page>/<slug>.fig`. Every `.fig` in those directories is
/// removed first, so a renamed family leaves nothing behind; the hand-written pages are not touched.
pub fn write_docs(docs: &Path, run_dir: &Path, series: &[SeriesStudy], comparison: &[CaseComparison]) {
    let families = docs.join(FAMILIES_DIR);
    for s in series {
        let dir = families.join(family_page(s.slug));
        if dir.is_dir() {
            for f in fs::read_dir(&dir).unwrap().flatten() {
                if f.path().extension().is_some_and(|e| e == "fig") {
                    fs::remove_file(f.path()).unwrap();
                }
            }
        }
    }
    for s in series {
        let dir = families.join(family_page(s.slug));
        fs::create_dir_all(&dir).unwrap();
        let file = format!("{}.fig", s.slug);
        fs::copy(run_dir.join(&file), dir.join(&file))
            .unwrap_or_else(|e| panic!("{}: {e}", run_dir.join(&file).display()));
    }
    write_naca456_page(&docs.join(NACA456_PAGE), series, comparison);
}

fn write_naca456_page(page: &Path, series: &[SeriesStudy], comparison: &[CaseComparison]) {
    let mut f = fs::File::create(page).unwrap();
    writeln!(f, "# Generated sections against naca456\n").unwrap();
    writeln!(
        f,
        "Generated by `cargo run --release -p geometry-validation -- --docs` from the generators in \
         `src/geometry/series/` and the naca456 fixtures in `tests/fixtures/naca456/` (`--render <run_dir> --docs` \
         rewrites it from an existing run folder); nothing on this page is hand-fed.\n"
    )
    .unwrap();
    writeln!(
        f,
        "Every analysis starts from a geometry yFoil generated, and the reference XFOIL analyses those same panels \
         ([the bitwise geometry handoff](../fidelity-to-xfoil/fixtures.md#the-bitwise-geometry-handoff)). That \
         proves both codes analyse the same panels; it does not prove the panels are the section the designation \
         names. This page checks that: every NACA generator is compared with an independent implementation of the \
         NACA definitions, the public-domain naca456 program. The definitions themselves, with a figure of each \
         family across its parameters, are in [Aerofoil families]({USING}/aerofoil-families/index.md).\n"
    )
    .unwrap();

    writeln!(f, "## Ordinate differences by family\n").unwrap();
    writeln!(f, "{}\n", comparison_note()).unwrap();
    for s in series {
        let rows: Vec<&CaseComparison> = comparison.iter().filter(|c| c.series == s.title).collect();
        writeln!(f, "### {} against naca456\n", s.title).unwrap();
        if rows.is_empty() {
            writeln!(
                f,
                "naca456 generates only the NACA families, so the {0} generator has no comparison against it; its \
                 definition is a closed-form conformal map ([{0}]({USING}/aerofoil-families/{1}.md)).\n",
                s.title,
                family_page(s.slug)
            )
            .unwrap();
        } else {
            writeln!(
                f,
                "The {} cases: the worst relative difference from naca456's ordinates over its stations. The family is \
                 defined in [Aerofoil families]({USING}/aerofoil-families/{}.md).\n",
                s.title,
                family_page(s.slug)
            )
            .unwrap();
            writeln!(f, "{}", comparison_table_md(&rows)).unwrap();
        }
    }

    writeln!(f, "## How the naca456 tables were produced\n").unwrap();
    writeln!(
        f,
        "`naca456` is Ralph L. Carmichael's public-domain revision (Public Domain Aeronautical Software, 2001; {}) \
         of the NASA Langley ordinate programs of TM X-3284, TM X-3069 and TM-4741 ({}), which compute the NACA \
         4-digit, 4-digit modified, 5-digit, 16-, 6- and 6A-series sections from their defining reports. It is the \
         reference because it is independent of both XFOIL and yFoil, it is public and pinned \
         (`scripts/naca456-fixtures.sh` fetches the package and checks its SHA-256), and it implements the \
         definitions as NASA tabulated them, including the 6-series, which has no closed form and is defined by the \
         tabulated mapping functions of TM-4741.\n",
        reference_links(&["carmichael2001"]),
        reference_links(&["ladson1975", "ladson1974", "ladson1996"])
    )
    .unwrap();
    writeln!(
        f,
        "`scripts/naca456-fixtures.sh` builds a driver on naca456's own modules, unchanged, in double precision with \
         fused multiply-add off, and writes every case of `scripts/naca456-fixtures/cases.txt` to \
         `tests/fixtures/naca456/` at 17 significant figures, with the provenance in `manifest.json`. \
         `tests/application/naca456.rs` tests every case: the thickness form and its slope, the mean line and its \
         slope, and the combined upper and lower surfaces at naca456's 98 \"very fine\" stations.\n"
    )
    .unwrap();
    writeln!(
        f,
        "**The tolerances are naca456's own precision**, not an engineering allowance: the closed-form families are \
         the same polynomials evaluated in a different association and agree to round-off; the 6-series and 6A mean \
         lines carry naca456's 10-digit π; and the 6-series thickness forms carry its 1e-6 root tolerance, scaled by \
         the slope of the thickness form. The constants are `TOL_NACA456_*` and `NACA456_ROOT_TOL` in \
         `tests/common/utilities/tolerances.rs`, each with its derivation.\n"
    )
    .unwrap();
}
